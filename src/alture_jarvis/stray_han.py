_LONGEST_MEANING = max(len(word) for word in MEANINGS)


def _by_meaning(run: str) -> str:
    """토막 **전체**가 아는 낱말들로 나뉘면 그 뜻을 이어 붙인 글. 한 조각이라도 모르면 빈 문자열(그러면 지운다)."""
    out: list[str] = []
    at = 0
    while at < len(run):
        for size in range(min(_LONGEST_MEANING, len(run) - at), 1, -1):
            word = MEANINGS.get(run[at : at + size])
            if word:
                out.append(word)
                at += size
                break
        else:
            return ""
    return "".join(out)


def mend(text: str) -> tuple[str, list[str]]:
    """짧게 끼어든 한자를 고친 글과, **손댄 토막 목록**(바꾼 것은 「測→측」 꼴)을 돌려준다.

    목록은 버리지 않는다 — 호출부가 사건으로 남겨야 얼마나 자주 튀는지 잴 수 있다.
    """
    if not text:
        return text, []
    touched: list[str] = []
    removed_any = False

    def fix(match: "re.Match[str]") -> str:
        nonlocal removed_any
        run = match.group(0)
        if len(run) > MAX_RUN:
            return run
        before = text[match.start() - 1] if match.start() else ""
        after = text[match.end()] if match.end() < len(text) else ""
        sound = READINGS.get(run) if len(run) == 1 else None
        if sound and (
            (_HANGUL.match(before) and before + sound in WORDS)
            or (_HANGUL.match(after) and sound + after in WORDS)
        ):
            touched.append(f"{run}→{sound}")
            return sound
        # 한글 문장 속(바로 옆이나 한 칸 건너가 한글)의 아는 중국어 낱말은 뜻으로 바꾼다.
        #   끝난 문장 바로 뒤에 붙은 것(「…방법입니다设置인데요」)은 문장의 낱말이 아니라 **군더더기**다 — 그건 예전처럼 지운다.
        near = text[max(0, match.start() - 2) : match.start()] + text[match.end() : match.end() + 2]
        tacked_on = bool(_SENTENCE_END.search(text[max(0, match.start() - 3) : match.start()]))
        meaning = _by_meaning(run) if len(run) > 1 and _HANGUL.search(near) and not tacked_on else ""
        if meaning:
            touched.append(f"{run}→{meaning}")
            return meaning
        touched.append(run)
        removed_any = True
        return ""

    cleaned = HAN.sub(fix, text)

    def drop(match: "re.Match[str]") -> str:
        touched.append(match.group(0))
        return ""

    cleaned = _WEDGED.sub(drop, cleaned)
    if not touched:
        return text, []
    if removed_any:
        # 글자를 지운 자리에 남는 공백 찌꺼기("입니다  인데요" → "입니다 인데요").
        cleaned = re.sub(r"[ \t]{2,}", " ", cleaned)
    return cleaned, touched
